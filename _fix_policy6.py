#!/usr/bin/env python3
with open('AGENTS.md', 'r', encoding='utf-8') as f:
    text = f.read()

old = '**1. РЕЗУЛЬТАТ ИЛИ ИНФРАСТРУКТУРА?:** Ведёт к деньгам? НЕТ → пропустить.\n\n**2. ВЕРИФИКАЦИЯ:** Результат РЕАЛЬНЫЙ? (не «файл есть», а «работает»)\n\n**3. ПРАВДА ИЛИ УПАКОВКА?:**'

new = '**1. РЕЗУЛЬТАТ ИЛИ ИНФРАСТРУКТУРА?:**\n- Ведёт к деньгам напрямую? → ДА → делай\n- Ведёт к деньгам через инфраструктуру? (чинит систему, закрывает дыру, ускоряет) → ДА → делай\n- Не ведёт к деньгам ни напрямую, ни через инфраструктуру? → НЕТ → пропусти\n\n*Чинить heartbeat* — не деньги, но без heartbeat система умрёт. Делай.\n*Писать отчёт о том как чинил heartbeat* — не деньги и не инфраструктура. Пропусти.\n\n**2. ВЕРИФИКАЦИЯ:** Результат РЕАЛЬНЫЙ? (не «файл есть», а «работает»)\n\n**3. ПРАВДА ИЛИ УПАКОВКА?:**'

assert old in text, "old not found in file"
text = text.replace(old, new, 1)
with open('AGENTS.md', 'w', encoding='utf-8') as f:
    f.write(text)
print('OK')
